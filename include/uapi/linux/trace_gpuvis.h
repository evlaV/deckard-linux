/*
 * <linux/trace_gpuvis.h> (#include <trace/gpuvis.h> from within-kernel)
 *
 * These are ftrace helpers that generate ftrace `print` events that can
 * be consumed from `gpuvis` (https://github.com/mikesart/gpuvis) and
 * `perfetto` (https://https://perfetto.dev).
 *
 * Typical usage looks like this:
 *
 *     void some_function()
 *     {
 *         TRACE_BEGIN_CTX();
 *         // do something...
 *     }
 *
 * This will automatically emit ftrace events to mark when this function
 * starts and finishes.  The full set of macros to be used are:
 *
 *    - TRACE_BEGIN_CTX(...): Instantly mark function start, use
 *      `__attribute__((cleanup)` compiler support to mark function end.
 *      Including a printf-style format string and arguments allows customizing
 *      the ftrace output with extra information.
 *
 *    - TRACE_END_CTX(...): Allows manual specification of the end point of the
 *      function, overriding the autogenerated trace point that would be emitted
 *      when the scope that contains the `TRACE_BEGIN_CTX()` ends.  This allows
 *      for precise notation of the line number of the exit of a function with
 *      complicated control flow.  An optional printf format string is also
 *      allowed here.
 *
 *    - TRACE_{BEGIN,END}_CTX_NAMED(name, ...): If you want to create multiple
 *      contexts within a single scope block, you must provide a unique `name`
 *      argument that is a valid variable name (a symbol, not a string).
 *
 * Conditional trace emission via a paired set of macros:
 *
 *    - TRACE_BEGIN_CTX_CONDITIONAL(name, ...)
 *      TRACE_END_CTX_CONDITIONAL(name, condition, ...): If `condition` evalutes
 *      to `true` emits both the begin and end events, allowing rare events to
 *      be traced without drowning the system in ftrace events.  Note that you
 *      _must_ pair conditional macros; attempting to mix, `TRACE_BEGIN_CTX()`
 *      with `TRACE_END_CTX_CONDITIONAL()` will result in a compiler error.
 *      There are some helper macros at the bottom of this file such as
 *      `TRACE_LONGER_THAN(us)` which suppresses printing unless the duration
 *      of the trace is longer than `us` microseconds, which is a common case.
 *
 *
 * Some helpful usage notes:
 *
 *    - To trace at finer granularity within a single function, you can use
 *      the `_NAMED()` variants of the macros to provide unique sub-function
 *      names to each segment of the function.  You can also use the `END`
 *      macro to explicitly end a sub-function segment at a particular point.
 *      For a quick-and-dirty solution, you can also use `TRACE_CTX_BEGIN()`
 *      inside manual scope blocks.
 *
 *    - All of these macros will automatically add file and line number
 *      information to the logged information, unless it is specifically
 *      suppressed by concatenating `TRACE_BASIC` to the beginning of the
 *      format string.
 *
 *    - Complex conditionals can be subbed off to functions that operate
 *      on the internal `gpuvis_trace_context_t` objects.
 *
 *    - By default, `TRACE_END_CTX()` calls inherit most information from
 *      their corresponding `TRACE_BEGIN_CTX()` call, such as payload.
 *      To manually prevent this, simply set the payload to `" "` or even
 *      `TRACE_BASIC`, to suppress file/line information as well.
 *
 *
 * Here is an example of all four usage notes at once, in the form of a userspace
 * program that will print the log entries out to `stdout` (rather than writing
 * to `/sys/kernel/tracing/trace_marker`) when compiled with the special
 * preprocessor define `-DTRACE_STDOUT_OVERRIDE`.
 *

#include <linux/trace_gpuvis.h>

bool my_custom_conditional(struct gpuvis_trace_context_t * begin_ctx)
{
    return strstr(begin_ctx->payload, "secret_number=10") != NULL;
}

int main()
{
    TRACE_BEGIN_CTX(TRACE_BASIC "This will not show line information");
    {
        TRACE_BEGIN_CTX_CONDITIONAL(name, "secret_number=10");
        TRACE_END_CTX_CONDITIONAL(my_custom_conditional(begin_ctx), name, TRACE_BASIC);
    }

    TRACE_BEGIN_CTX_NAMED(other, "This starts after the first trace");
}

 * Place that code in `tracing_test.c` in the kernel root directory then run:
 *
 *     cc -g -o /tmp/tracing_test -DTRACE_STDOUT_OVERRIDE -I./include tracing_test.c && /tmp/tracing_test
 *
 * And you should see output such as:
 *
 *     [main] begin_ctx=1 tgid=1001 This will not show line information
 *     [main.name] begin_ctx=2 dtime=-313 tgid=1001 file=tracing_test.c:12 secret_number=10
 *     [main.name] end_ctx=2 tgid=1001
 *     [main.other] begin_ctx=3 tgid=1001 file=tracing_test.c:16 This starts after the first trace
 *     [main.other] end_ctx=3 tgid=1001 This starts after the first trace
 *     [main] end_ctx=1 tgid=1001 This will not show line information
 */


